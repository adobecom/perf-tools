#!/usr/bin/env node
// perf-site-preloads: merges perf-preload recordings of several pages (mobile and --desktop) into the site's inline
// head.html preloads block (prelink/site-head.html with its LINKS and LOCALES filled in, see lib/site-preloads.mjs).
import fs from 'node:fs';
import path from 'node:path';
import { parseArgs } from 'node:util';
import { fileURLToPath } from 'node:url';
import { buildSitePreloads, rootLocale, usesPlaceholder, headSnippet } from '../lib/site-preloads.mjs';

const TEMPLATE = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'prelink', 'site-head.html');
const BEGIN = '<!-- site preloads: generated by perf-site-preloads (adobecom/perf-tools), regenerate instead of editing -->';
const END = '<!-- end of site preloads -->';

const { values: o, positionals } = parseArgs({
  allowPositionals: true,
  options: {
    out: { type: 'string', short: 'o' },
    into: { type: 'string' },
    global: { type: 'string' },
    markets: { type: 'string' },
    help: { type: 'boolean', short: 'h' },
  },
});

if (o.help || !positionals.length || !(o.out || o.into)) {
  console.log(`perf-site-preloads <links.json|dir> [...] (-o <site-preloads.html> | --into <head.html>) [--global <pattern|none>] [--markets <url|file>]

  Merges perf-preload outputs (<page-key>.links.json and <page-key>.desktop.links.json: record each page with
  perf-preload and perf-preload --desktop) into one inline <script> for the site's head.html: rows that carry the
  pages they apply to (path patterns), the viewport (all, mobile, desktop) and the link attributes. No request at run
  time; updating the preloads means regenerating head.html. A link recorded on every page becomes a global row
  (--global, default: the pages' common directory, e.g. /acrobat/**; "none" keeps page lists); a link recorded on
  mobile and desktop for the same pages becomes one "all" row. Milo and MAS library URLs become {milolibs} / {maslibs}
  and MAS fragment URLs ?...&locale={locale}&country={country}, resolved on the page (milolibs/maslibs query
  parameters, MAS geo detection, markets). LOCALES holds the root site's markets from Milo's supported-markets.json
  (--markets, default: the supported-markets.json the pages fetched, else
  <origin>/federal/assets/supported-markets/supported-markets.json).

  -o, --out <file>      write the block to a file (outside the repository, e.g. ~/perf-ab-runs/<run>/site-preloads.html)
  --into <head.html>    put the block into a site's head.html: replaces the previous generated block, or goes right
                        after <meta name="viewport"> (EDS renders the page's metadata before head.html; the viewport
                        must be set for the mobile/desktop media queries)
  --global <pattern>    pattern for links recorded on every page, or "none"
  --markets <url|file>  Milo supported-markets.json to read the root site's markets from`);
  process.exit(o.help ? 0 : 1);
}

const fail = (m) => { console.error(`perf-site-preloads: ${m}`); process.exit(1); };
const files = positionals.flatMap((p) => {
  const abs = path.resolve(p);
  if (!fs.existsSync(abs)) fail(`${p}: not found`);
  if (!fs.statSync(abs).isDirectory()) {
    if (!abs.endsWith('.links.json')) fail(`${p}: expected a <page-key>.links.json file or a perf-preload output directory`);
    return [abs];
  }
  const found = fs.readdirSync(abs).filter((f) => f.endsWith('.links.json')).map((f) => path.join(abs, f));
  if (!found.length) fail(`${p}: no <page-key>.links.json (record the page with this version of perf-preload)`);
  return found;
});
const inputs = files.map((f) => {
  try { return JSON.parse(fs.readFileSync(f, 'utf8')); } catch (e) { return fail(`${f}: ${e.message}`); }
});

let result;
try {
  result = buildSitePreloads(inputs, { global: o.global === 'none' ? null : o.global });
} catch (e) { fail(e.message); }

const locales = [];
if (usesPlaceholder(result.rows, 'country') || usesPlaceholder(result.rows, 'locale')) {
  const origin = new URL(inputs[0].page).origin;
  const recorded = inputs.flatMap((d) => d.links.map((l) => l.url)).find((u) => /\/supported-markets\/[^/]+\.json$/.test(new URL(u).pathname));
  const source = o.markets ?? recorded ?? `${origin}/federal/assets/supported-markets/supported-markets.json`;
  let markets;
  try {
    if (/^https:\/\//.test(source)) {
      const res = await fetch(source, { signal: AbortSignal.timeout(30000) });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      markets = await res.json();
    } else {
      markets = JSON.parse(fs.readFileSync(source, 'utf8'));
    }
  } catch (e) { fail(`cannot read the supported markets from ${source}: ${e.message}`); }
  const locale = rootLocale(markets);
  if (!locale.supportedRegions) fail(`${source}: no supported regions for the root site`);
  locales.push(locale);
  console.log(`locales: root site en_US, default market ${locale.defaultMarket}, ${locale.supportedRegions.split(',').length} supported regions (${source})`);
}

const recordings = inputs.map((d) => `${new URL(d.page).pathname} ${d.device}`).sort();
const note = `${recordings.length} recordings: ${recordings.join(', ')}`;
let block;
try {
  block = `${BEGIN}\n${headSnippet(fs.readFileSync(TEMPLATE, 'utf8'), { rows: result.rows, locales, note }).trimEnd()}\n${END}\n`;
} catch (e) { fail(e.message); }

if (o.out) {
  const out = path.resolve(o.out);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, block);
  console.log(`site preloads block: ${out}`);
}
if (o.into) {
  const head = path.resolve(o.into);
  let html;
  try { html = fs.readFileSync(head, 'utf8'); } catch (e) { fail(`--into ${o.into}: ${e.message}`); }
  const start = html.indexOf(BEGIN);
  let next;
  if (start >= 0) {
    const end = html.indexOf(END, start);
    if (end < 0) fail(`--into ${o.into}: generated block without its end marker`);
    next = `${html.slice(0, start)}${block}${html.slice(end + END.length).replace(/^\n/, '')}`;
  } else {
    const viewport = html.match(/<meta name="viewport"[^>]*>\n?/);
    if (!viewport) fail(`--into ${o.into}: no <meta name="viewport"> to place the block after`);
    const at = viewport.index + viewport[0].length;
    next = `${html.slice(0, at)}${viewport[0].endsWith('\n') ? '' : '\n'}${block}${html.slice(at)}`;
  }
  fs.writeFileSync(head, next);
  console.log(`${start >= 0 ? 'updated' : 'added'} the site preloads block in ${head}`);
}

console.log(`recordings: ${inputs.map((d) => `${new URL(d.page).pathname} (${d.device}, LCP ${d.lcp?.median ?? '?'} ms)`).join(', ')}`);
console.log(`global pattern: ${result.global ?? '(none)'}`);
const count = {};
for (const r of result.rows) {
  const scope = r.pages === result.global ? 'global' : r.pages.includes(',') ? 'shared' : 'page';
  count[`${scope}/${r.viewport}`] = (count[`${scope}/${r.viewport}`] ?? 0) + 1;
}
console.log(`links: ${result.rows.length} rows (${Object.entries(count).map(([k, v]) => `${k} ${v}`).join(', ')}), block ${Buffer.byteLength(block)} bytes`);
for (const [url, why] of result.skipped) console.log(`  skipped ${url}: ${why}`);
